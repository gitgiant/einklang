/** Glyph rows by code point: 8 strings of 5. */
export const PIXEL_5x8: Map<number, string[]> = new Map(
  DATA.trim().split('\n').map((line) => {
    const [code, ...rows] = line.trim().split(/\s+/);
    if (rows.length !== 8 || rows.some((r) => r.length !== 5)) throw new Error(`pixel font: bad glyph ${code}`);
    return [+code, rows];
  }),
);
